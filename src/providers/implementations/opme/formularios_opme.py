def normalizar_codigo_aghu(valor) -> str:
    """Só dígitos e sem zeros à esquerda — "0087446" e "87446" são o mesmo."""
    digitos = "".join(c for c in str(valor or "") if c.isdigit())
    return digitos.lstrip("0") or ("0" if digitos else "")


def codigos(texto_codigos: str) -> list[str]:
    return [c for c in (normalizar_codigo_aghu(p) for p in str(texto_codigos or "").replace("/", " ")
                        .replace(",", " ").split()) if c]


def linhas(chave: str) -> list[dict]:
    """Linhas do formulário numeradas (a posição identifica a linha)."""
    form = FORMULARIOS.get(chave)
    if not form:
        return []
    return [{"linha": n, "codigos": " ".join(codigos(cod)), "descricao": desc,
             "pede_especificacao": not codigos(cod) or desc.rstrip().endswith(":")}
            for n, (cod, desc) in enumerate(form["linhas"], start=1)]


def sugerido(especialidade: str, unidade: str = "") -> str:
    especialidade, unidade = (especialidade or "").upper(), (unidade or "").upper()
    if unidade.startswith("HEMODINAMICA"):
        return "hemodinamica"
    for chave, form in FORMULARIOS.items():
        if especialidade in form["sugerido_para"]:
            return chave
    return ""
